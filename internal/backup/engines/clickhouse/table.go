package clickhouse

import "strings"

// The restore generates every CREATE TABLE from structured data and never
// runs DDL text from the backup:
//
//	CREATE TABLE `db`.`table` (`col` Type, …) ENGINE = Engine[(args)]
//	  [PARTITION BY …] ORDER BY … [PRIMARY KEY …] [SETTINGS allow_nullable_key = 1]
//
// - columns: the ordinary columns (those in the backup's data), names
//   quoted by Olympos, types read by the strict grammar (types.go) and
//   written again;
// - engine: the manifest's, from an allowlist; its parameters are bare
//   columns of the table, read from the schema entry's ENGINE clause only
//   for the engines that take them; Replicated tables get a Keeper path
//   generated by Olympos;
// - keys: the manifest's sorting, partition and primary keys when they are
//   bare columns (or one of a few date partition forms, generated by
//   Olympos); otherwise a MergeTree table gets ORDER BY tuple() and no
//   partition key, and a table of an engine that merges rows (Replacing,
//   Summing, Aggregating, Collapsing) is not created.
//
// Defaults, MATERIALIZED, ALIAS and EPHEMERAL columns, codecs, TTL,
// indexes, projections, constraints, comments, the sampling key and
// settings are not restored; the result says so per table.

func kindWord(kind string) string {
	switch kind {
	case KindTable, KindMVInner:
		return "table"
	case KindView:
		return "view"
	case KindMaterializedView:
		return "materialized view"
	case KindDictionary:
		return "dictionary"
	case KindOther:
		return "live or window view"
	}
	return kind
}

// notRecreated is the reason for views, materialized views, dictionaries
// and live or window views.
const notRecreated = "not created: recreate it from your schema (Olympos restores tables and data)"

// ---------------------------------------------------------------- engines

// tableEngines keep their data on the target and read nothing else; with
// the Replicated variants of the MergeTree ones they are the only engines a
// restore creates.
var tableEngines = map[string]bool{
	"MergeTree": true, "ReplacingMergeTree": true, "SummingMergeTree": true, "AggregatingMergeTree": true,
	"CollapsingMergeTree": true, "VersionedCollapsingMergeTree": true,
	"Log": true, "TinyLog": true, "StripeLog": true, "Memory": true,
}

// splitEngine returns the engine without "Replicated" and whether it had
// it; ok is false for engines a restore does not create.
func splitEngine(engine string) (base string, replicated, ok bool) {
	if tableEngines[engine] {
		return engine, false, true
	}
	if b, cut := strings.CutPrefix(engine, "Replicated"); cut && isMergeTree(b) && tableEngines[b] {
		return b, true, true
	}
	return engine, false, false
}

func engineSkipReason(engine string) string {
	switch {
	case engine == "Distributed":
		return "engine Distributed points at a cluster"
	case strings.HasSuffix(engine, "GraphiteMergeTree"):
		return "engine " + engine + " is not restored by Olympos (its rollup rules live in the server configuration); create it by hand"
	}
	return "engine " + engine + " is not restored by Olympos (it restores MergeTree, Log and Memory tables)"
}

// ---------------------------------------------------------------- columns

// column is a restored column: its name and the type Olympos wrote.
type column struct{ name, typ string }

// columnSet maps the restored columns' names to their types.
type columnSet map[string]string

// columnList reads a list of bare column names of cols: "a", "a, b",
// "(a, b)", "tuple(a, b)", "tuple()" or nothing. ok is false for anything
// else.
func columnList(toks []token, cols columnSet) ([]string, bool) {
	if len(toks) == 0 {
		return nil, true
	}
	last := len(toks) - 1
	switch {
	case toks[0].kind == tokWord && toks[0].val == "tuple" && tokenAt(toks, 1).punct("(") && matching(toks, 1) == last:
		toks = toks[2:last]
	case toks[0].punct("(") && matching(toks, 0) == last:
		toks = toks[1:last]
	}
	var out []string
	for i, t := range toks {
		if i%2 == 1 {
			if !t.punct(",") {
				return nil, false
			}
			continue
		}
		if !t.ident() {
			return nil, false
		}
		if _, ok := cols[t.val]; !ok {
			return nil, false
		}
		out = append(out, t.val)
	}
	if len(toks) > 0 && len(toks)%2 == 0 { // a trailing comma
		return nil, false
	}
	return out, true
}

// keyColumns reads a key of the manifest (system.tables' sorting_key,
// primary_key) that is only column names.
func keyColumns(expr string, cols columnSet) ([]string, bool) {
	if len(expr) > maxTypeText {
		return nil, false
	}
	toks, err := lexSQL(expr)
	if err != nil {
		return nil, false
	}
	return columnList(toks, cols)
}

// partitionFunctions are the partition forms Olympos writes itself around
// one column.
var partitionFunctions = map[string]bool{"toYYYYMM": true, "toYYYYMMDD": true, "toDate": true, "toStartOfMonth": true}

// partitionKey generates the partition key from the manifest's: bare
// columns, or f(column) with f in partitionFunctions. "" with ok: no
// partition key.
func partitionKey(expr string, cols columnSet) (key string, keyCols []string, ok bool) {
	if len(expr) > maxTypeText {
		return "", nil, false
	}
	toks, err := lexSQL(expr)
	if err != nil {
		return "", nil, false
	}
	if len(toks) == 4 && toks[0].kind == tokWord && partitionFunctions[toks[0].val] && toks[1].punct("(") &&
		toks[2].ident() && toks[3].punct(")") {
		if _, ok := cols[toks[2].val]; ok {
			return toks[0].val + "(" + quoteIdent(toks[2].val) + ")", []string{toks[2].val}, true
		}
		return "", nil, false
	}
	names, ok := columnList(toks, cols)
	if !ok {
		return "", nil, false
	}
	return keyExpr(names, ""), names, true
}

// keyExpr writes a column list: one column bare, several as a tuple, none
// as empty (or "tuple()" when empty is "tuple()").
func keyExpr(names []string, empty string) string {
	switch len(names) {
	case 0:
		return empty
	case 1:
		return quoteIdent(names[0])
	}
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = quoteIdent(n)
	}
	return "(" + strings.Join(q, ", ") + ")"
}

func isPrefix(p, of []string) bool {
	if len(p) > len(of) {
		return false
	}
	for i := range p {
		if p[i] != of[i] {
			return false
		}
	}
	return true
}

// ---------------------------------------------------------------- engine parameters

// argColumn: one argument that is a bare column of cols.
func argColumn(a []token, cols columnSet) (string, bool) {
	if len(a) != 1 || !a[0].ident() {
		return "", false
	}
	if _, ok := cols[a[0].val]; !ok {
		return "", false
	}
	return a[0].val, true
}

// engineNeedsArgs: engines whose parameters are columns; without them the
// table would behave differently.
var engineNeedsArgs = map[string]bool{
	"ReplacingMergeTree": true, "SummingMergeTree": true, "CollapsingMergeTree": true, "VersionedCollapsingMergeTree": true,
}

// engineArgs generates the parameters of engine base from the schema
// entry's ENGINE arguments (Keeper path and replica already removed): bare
// columns of the table, in the shape the engine takes.
func engineArgs(base string, args [][]token, cols columnSet) ([]string, bool) {
	columns := func(min, max int) ([]string, bool) {
		if len(args) < min || len(args) > max {
			return nil, false
		}
		var out []string
		for _, a := range args {
			c, ok := argColumn(a, cols)
			if !ok {
				return nil, false
			}
			out = append(out, quoteIdent(c))
		}
		return out, true
	}
	switch base {
	case "ReplacingMergeTree": // ([ver[, is_deleted]])
		return columns(0, 2)
	case "CollapsingMergeTree": // (sign)
		return columns(1, 1)
	case "VersionedCollapsingMergeTree": // (sign, version)
		return columns(2, 2)
	case "SummingMergeTree": // ([columns]): a column or a tuple of columns
		switch len(args) {
		case 0:
			return nil, true
		case 1:
			names, ok := columnList(args[0], cols)
			if !ok || len(names) == 0 {
				return nil, false
			}
			return []string{keyExpr(names, "")}, true
		}
		return nil, false
	}
	return nil, len(args) == 0
}

// ---------------------------------------------------------------- CREATE TABLE

// tableDef is a generated CREATE TABLE.
type tableDef struct {
	sql         string
	keeperPath  string   // the Replicated table's Keeper path ("" otherwise)
	notRestored []string // what of the source table is not restored
}

// keeperPath is the Keeper path of a restored Replicated table: under
// /olympos-restore/<request id>/, then the database and table names
// escaped as ClickHouse escapes file names ([A-Za-z0-9_] kept, every other
// byte %XX), so a name can add no path component and no macro.
func keeperPath(requestID, db, table string) string {
	return "/olympos-restore/" + requestID + "/" + escapeForFileName(db) + "/" + escapeForFileName(table)
}

// replicaName is the replica of a restored Replicated table: the target's
// {replica} macro (without it, the target refuses the CREATE).
const replicaName = "{replica}"

// buildTable generates the CREATE TABLE of table t of database db, named
// target on the target. ddl is t's schema entry ("" when the backup has
// none readable); it is only read for the ENGINE parameters of
// engineNeedsArgs. requestID must already be checked (requestIDRe). why is
// set when the table is not created.
func buildTable(db, target string, t Table, ddl, requestID string) (*tableDef, string) {
	base, replicated, ok := splitEngine(t.Engine)
	if !ok {
		return nil, engineSkipReason(t.Engine)
	}
	def := &tableDef{}

	// Columns.
	cols := columnSet{}
	var list []column
	var defaults, computed []string
	for _, c := range t.Columns {
		switch c.DefaultKind {
		case "", "DEFAULT":
		case "MATERIALIZED", "ALIAS", "EPHEMERAL":
			computed = append(computed, quoteIdent(c.Name))
			continue
		default:
			return nil, "column " + quoteIdent(c.Name) + " is of a kind Olympos does not read"
		}
		if c.Name == "" {
			return nil, "a column of it has no name"
		}
		if _, dup := cols[c.Name]; dup {
			return nil, "column " + quoteIdent(c.Name) + " appears twice"
		}
		ty, err := canonicalType(c.Type)
		if err != nil {
			return nil, "column " + quoteIdent(c.Name) + " has a type Olympos does not restore"
		}
		if c.DefaultKind == "DEFAULT" {
			defaults = append(defaults, quoteIdent(c.Name))
		}
		cols[c.Name] = ty
		list = append(list, column{c.Name, ty})
	}
	if len(list) == 0 {
		return nil, "the backup records no columns it can restore"
	}

	// Engine parameters.
	var args []string
	if engineNeedsArgs[base] {
		name, src, err := sourceEngine(ddl)
		if err != nil {
			return nil, "its engine parameters could not be read from its schema entry"
		}
		if name != t.Engine {
			return nil, "its schema entry names engine " + name + ", the backup recorded " + t.Engine
		}
		if replicated {
			switch {
			case len(src) >= 2 && len(src[0]) == 1 && src[0][0].kind == tokString && len(src[1]) == 1 && src[1][0].kind == tokString:
				src = src[2:]
			case len(src) >= 1 && len(src[0]) == 1 && src[0][0].kind == tokString:
				return nil, "its engine parameters could not be read from its schema entry"
			}
		}
		var ok bool
		if args, ok = engineArgs(base, src, cols); !ok {
			return nil, "its " + base + " parameters are not columns of the table (they change how its rows merge)"
		}
	}
	if replicated {
		def.keeperPath = keeperPath(requestID, db, target)
		args = append([]string{quoteString(def.keeperPath), quoteString(replicaName)}, args...)
	}

	var b strings.Builder
	b.WriteString("CREATE TABLE " + qualified(db, target) + " (")
	for i, c := range list {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(quoteIdent(c.name) + " " + c.typ)
	}
	b.WriteString(") ENGINE = " + t.Engine)
	if len(args) > 0 || replicated {
		b.WriteString("(" + strings.Join(args, ", ") + ")")
	}

	var lost []string
	if len(defaults) > 0 {
		lost = append(lost, "the DEFAULT expressions of "+strings.Join(defaults, ", "))
	}
	if len(computed) > 0 {
		lost = append(lost, "the MATERIALIZED, ALIAS and EPHEMERAL columns "+strings.Join(computed, ", ")+" (not in the backup's data)")
	}
	if isMergeTree(base) {
		var keyCols []string
		// Replacing, Summing, Aggregating, Collapsing and VersionedCollapsing
		// tables merge rows by their sorting key within a partition: with
		// other keys their rows would merge differently, so such a table is
		// only created with both keys as the source had them.
		merges := base != "MergeTree"
		partition, pcols, ok := partitionKey(t.PartitionKey, cols)
		if !ok {
			if merges {
				return nil, "its partition key is not a column list or a date form Olympos restores (another key changes how its rows merge)"
			}
			lost = append(lost, "its partition key (the table has none)")
			partition = ""
		}
		keyCols = append(keyCols, pcols...)
		order, ok := keyColumns(t.SortingKey, cols)
		if !ok {
			if merges {
				return nil, "its sorting key is not a column list (another key changes how its rows merge)"
			}
			lost = append(lost, "its sorting key (ORDER BY tuple() instead)")
			order = nil
		}
		if base == "VersionedCollapsingMergeTree" && len(order) > 0 && len(args) > 0 && quoteIdent(order[len(order)-1]) == args[len(args)-1] {
			// The server appends the version column to the sorting key it
			// reports; it does so again on the target.
			order = order[:len(order)-1]
		}
		keyCols = append(keyCols, order...)
		primary, ok := keyColumns(t.PrimaryKey, cols)
		switch {
		case !ok || !isPrefix(primary, order):
			if t.PrimaryKey != "" && t.PrimaryKey != t.SortingKey {
				lost = append(lost, "its primary key (the sorting key is used)")
			}
			primary = nil
		case len(primary) == len(order):
			primary = nil // the default
		}
		if partition != "" {
			b.WriteString(" PARTITION BY " + partition)
		}
		b.WriteString(" ORDER BY " + keyExpr(order, "tuple()"))
		if len(primary) > 0 {
			b.WriteString(" PRIMARY KEY " + keyExpr(primary, ""))
		}
		for _, k := range keyCols {
			if nullableKey.MatchString(cols[k]) {
				b.WriteString(" SETTINGS allow_nullable_key = 1")
				break
			}
		}
		lost = append(lost, "any codecs, TTL, indexes, projections, constraints, comments, sampling key and settings")
	} else {
		lost = append(lost, "any codecs, constraints, comments and settings")
	}
	def.sql = b.String()
	def.notRestored = lost
	return def, ""
}

// databaseSQL is the CREATE DATABASE of a restored database.
func databaseSQL(db string) string { return "CREATE DATABASE " + quoteIdent(db) + " ENGINE = Atomic" }
